export function getConduitFillLimit(cableCount: number): {
  allowablePercent: number;
  referenceTable: string;
  sourceStatus: SourceStatus;
  note: string;
} {
  if (cableCount <= 1) {
    return {
      allowablePercent: 53,
      referenceTable: 'ตารางที่ 5-3',
      sourceStatus: 'VERIFIED_STANDARD_DATA',
      note: 'สาย 1 เส้น ยอมให้ใช้พื้นที่ได้ 53%',
    };
  }
  if (cableCount === 2) {
    return {
      allowablePercent: 31,
      referenceTable: 'ตารางที่ 5-3',
      sourceStatus: 'VERIFIED_STANDARD_DATA',
      note: 'สาย 2 เส้น ยอมให้ใช้พื้นที่ได้ 31%',
    };
  }
  return {
    allowablePercent: 40,
    referenceTable: 'ตารางที่ 5-3',
    sourceStatus: 'VERIFIED_STANDARD_DATA',
    note: 'สาย 3 เส้นขึ้นไป ยอมให้ใช้พื้นที่ได้ 40%',
  };
}

